dir.create("output", showWarnings=FALSE)
d <- read.csv("data/failure_events.csv", stringsAsFactors=FALSE)
agg <- aggregate(cbind(event_count=rep(1,nrow(d)), lost_minutes=d$lost_minutes), list(category=d$category), sum)
agg <- agg[order(-agg$lost_minutes),]
agg$cumulative_pct <- round(100*cumsum(agg$lost_minutes)/sum(agg$lost_minutes),1)
write.csv(agg,"output/cause_pareto.csv",row.names=FALSE)
png("output/pareto_failures.png",1200,700)
bp <- barplot(agg$lost_minutes,names.arg=agg$category,las=2,col="#1F6FEB",ylab="Lost minutes",main="Pipeline failure Pareto")
par(new=TRUE); plot(bp,agg$cumulative_pct,type="o",pch=19,col="#F59E0B",axes=FALSE,xlab="",ylab="",ylim=c(0,100)); axis(4); mtext("Cumulative %",side=4,line=2)
dev.off()
five <- data.frame(level=paste0("Why ",1:5),statement="",evidence_or_hypothesis="",source="")
write.csv(five,"output/five_whys_template.csv",row.names=FALSE)
