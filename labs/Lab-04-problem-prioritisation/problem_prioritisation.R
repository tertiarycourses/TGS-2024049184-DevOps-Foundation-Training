dir.create("output",showWarnings=FALSE)
d <- read.csv("data/problems.csv",stringsAsFactors=FALSE)
score_cols <- c("severity","frequency","business_impact","confidence","effort")
stopifnot(all(unlist(d[score_cols])>=1),all(unlist(d[score_cols])<=5))
d$priority_score <- round((d$severity*d$frequency*d$business_impact*(d$confidence/5))/d$effort,2)
d <- d[order(-d$priority_score,-d$severity,d$problem_id),]
d$rank <- seq_len(nrow(d))
write.csv(d,"output/problem_priority.csv",row.names=FALSE)
png("output/priority_matrix.png",1000,800)
plot(d$frequency,d$severity,pch=19,cex=1+d$business_impact/3,col="#1F6FEB",xlim=c(0.5,5.5),ylim=c(0.5,5.5),xlab="Frequency (1-5)",ylab="Severity (1-5)",main="Problem priority evidence")
text(d$frequency,d$severity,labels=d$problem_id,pos=3,cex=.8)
abline(v=3.5,h=3.5,lty=2,col="#F59E0B")
dev.off()
stopifnot(!anyDuplicated(d$rank),all(is.finite(d$priority_score)))
